"""Bounded original-law method review; no current source/category or court admission."""
from pathlib import Path
import gzip
import hashlib
import html
import json
import re
import subprocess
import tempfile
from urllib.parse import urljoin
import xml.etree.ElementTree as ET

DATA = Path(__file__).resolve().parent
ROOT = DATA.parent


def main():
    manifest = json.loads((DATA / 'news/manifest.json').read_bytes())
    pins = []

    def original(sid):
        row = next(x for x in manifest if x['id'] == sid)
        stored = (DATA / 'news' / row['asset']).read_bytes()
        raw = gzip.decompress(stored)
        assert hashlib.sha256(stored).hexdigest() == row['stored_sha256']
        assert hashlib.sha256(raw).hexdigest() == row['raw_sha256'] and len(raw) == row['bytes']
        pins.append(dict(row))
        return raw, row

    raw, parent = original('hb859-official-history')
    history = ET.fromstring(raw)
    assert history.findtext('./BACKGROUND/DISPOSITION') == 'Law'
    assert history.findtext('./BACKGROUND/EFFECTIVEDATE') == 'July 1, 2026'
    assert history.findtext('./BACKGROUND/CHAPNUM').strip() == '385'
    assert '03/19 Approved by Governor' in [x.text for x in history.findall('./ACTION/ACT_DESC')]
    pdf, pdf_meta = original('hb859-official-current-pdf')
    doc, html_meta = original('hb859-official-current-html')
    for meta, tag in [(pdf_meta, 'CURRENT_PDF'), (html_meta, 'CURRENT_OTHER')]:
        assert meta['url'] == urljoin(parent['final_url'], history.findtext('.//' + tag))
    assert b'charset=windows-1252' in doc[:1000]
    text = doc.decode('windows-1252')
    assert '<title>HB 859 (As Sent to Governor) - 2026 Regular Session</title>' in text
    text = re.sub(r'<(script|style)\b[^>]*>.*?</\1>', ' ', text, flags=re.S | re.I)
    text = ' '.join(html.unescape(re.sub(r'<[^>]*>', ' ', text)).split())
    assert 'daily report to be generated and printed by the OMR equipment' in text
    assert 'available to the public upon request' in text
    assert 'July 1, 2026' in text
    with tempfile.TemporaryDirectory() as t:
        p = Path(t) / 'original.pdf'
        p.write_bytes(pdf)
        pages = subprocess.check_output(['pdftotext', '-layout', str(p), '-']).decode().split('\f')
    assert '(As Passed the House)' in pages[0]
    assert 'SECTION 26.' in pages[48] and 'SECTION 27.' in pages[48]
    assert 'available to the public upon' in pages[48]
    assert 'after July 1, 2026.' in pages[48]
    assert 'not tallied until after closing of' in pages[7]
    assert 'the fifth business day after the election' in pages[7]
    previews = json.loads((DATA / 'coordinator-qa/hb859-page-renders.json').read_bytes())
    for row in previews:
        b = (ROOT / row['path']).read_bytes()
        assert len(b) == row['bytes'] and hashlib.sha256(b).hexdigest() == row['sha256']
    out = {
        'status': 'pass_bounded_official_history_and_method_text_with_document_label_disagreement',
        'original_pins': pins,
        'official_history': {'bill': 'HB859', 'year': 2026, 'disposition': 'Law', 'chapter': 385,
                             'approval_action_literal': '03/19 Approved by Governor',
                             'effective_date_literal': 'July 1, 2026'},
        'observed_document_labels': {'official_current_HTML': 'As Sent to Governor',
                                     'official_current_PDF_page1': 'As Passed the House',
                                     'scope': 'Both URLs are actual CURRENT document links in the retained official history. Preserve the different printed labels; no publication cause or version chronology inferred.'},
        'bounded_source_findings': {
            'section26': 'Daily aggregate number of in-person absentee ballots generated by OMR at close of business; circuit clerk must make report available on request.',
            'section27': 'July1,2026 effective date in both official current HTML and PDF, consistent with official history.',
            'section4_page8': 'Source text postpones tallying until polls close. Its preceding late-mail processing clause also survives; a general election-night counting instruction is not an exact remaining-vote or completion guarantee.',
            'daily_report_scope': 'Ballot administration, not Senate votes or a candidate/method release. No public endpoint, actual report, measured cadence or candidate allocation established.'},
        'independently_rendered_and_visually_read_complete_pages': previews,
        'limits': 'Operative code consolidation, subsequent laws/rules/orders, receipt/cure details and actual November method/result identifiers remain for the official-results assignment. This review does not infer physical precinct membership or a historical/current method crosswalk.'
    }
    (DATA / 'coordinator-absentee-method-law-review.json').write_text(json.dumps(out, indent=2) + '\n')
    print(json.dumps({'status': out['status'], 'official_originals': len(pins), 'chapter': 385,
                      'effective': '2026-07-01', 'daily_aggregate_report': True,
                      'printed_document_labels_differ': True}))


if __name__ == '__main__':
    main()
