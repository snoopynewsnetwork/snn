#!/usr/bin/env python3
"""Hash every owned file except this manifest itself; no other exclusions."""
import pathlib,hashlib,json
ROOT=pathlib.Path(__file__).resolve().parent;STATE=ROOT.parent.parent;target=ROOT/'asset-manifest.json'
files=sorted([STATE/'official-results.md',STATE/'data/official-results-sources.csv']+[p for p in ROOT.rglob('*') if p.is_file() and p!=target])
assert all('__pycache__'not in p.parts for p in files),'remove generated bytecode before freezing'
assets=[]
for p in files:
 b=p.read_bytes();assert len(b)<40000000,(p,len(b));assets.append({'path':str(p.relative_to(STATE)),'bytes':len(b),'sha256':hashlib.sha256(b).hexdigest()})
target.write_text(json.dumps({'schema_version':1,'scope':'exact owned report,CSV,and data/results-sources/**; self-exclusion only','excluded_paths':['data/results-sources/asset-manifest.json'],'assets':assets},indent=2)+'\n')
print('ownedassets',len(assets),'totalstoredbytes',sum(a['bytes'] for a in assets),'manifestsha256',hashlib.sha256(target.read_bytes()).hexdigest())
